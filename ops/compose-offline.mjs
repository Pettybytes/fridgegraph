#!/usr/bin/env node
/**
 * compose-offline — build the supergraph from COMMITTED SDL, not from a running checkout.
 *
 * THE DEFECT (2026-11-02, launcher scope)
 * `ops/alt-stack.sh` composed `supergraph.yaml` before starting its alternate subgraphs. That file points
 * every subgraph at `subgraph_url: http://127.0.0.1:4001..4007/`, so composition silently required
 * ANOTHER checkout to already be serving — and the resulting artifact carried the *other* stack's routing
 * URLs. A launcher that cannot start alone is not a launcher.
 *
 * WHAT THIS DOES
 * Writes a temporary rover config whose subgraphs point at `schema/<name>.graphql` (committed SDL) with
 * `routing_url` set to the PORTS THE CALLER INTENDS, composes it, and checks the artifact really contains
 * the federation fields the routers and MCP depend on.
 *
 * It never starts, stops or reads a running service, and it never needs one.
 *
 * Usage:
 *   node ops/compose-offline.mjs --out .runs/supergraph.graphql --base-port 4101
 *   node ops/compose-offline.mjs --out /tmp/sg.graphql --base-port 4001 --expect villageWorld,proposeAddVillager
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';

const SUBGRAPHS = ['village', 'access', 'coordination', 'schedule', 'school', 'transport', 'activities'];
const DEFAULT_EXPECT = ['villageWorld', 'proposeAddVillager', 'confirmAddVillager', 'pickupRideEstimate'];

const args = process.argv.slice(2);
const arg = (n, d) => { const i = args.indexOf(`--${n}`); return i >= 0 && args[i + 1] ? args[i + 1] : d; };

const out = arg('out', '.runs/supergraph.graphql');
const basePort = Number(arg('base-port', '4001'));
const schemaDir = resolve(arg('schema-dir', 'schema'));
const roverBin = arg('rover', join(process.env.HOME ?? '', '.rover', 'bin', 'rover'));
const expect = (arg('expect', '') || DEFAULT_EXPECT.join(','))
  .split(',').map((s) => s.trim()).filter(Boolean);

if (!Number.isInteger(basePort)) { console.error(`REFUSED: --base-port must be an integer, got ${basePort}`); process.exit(2); }

const missing = SUBGRAPHS.filter((n) => !existsSync(join(schemaDir, `${n}.graphql`)));
if (missing.length) {
  console.error(`REFUSED: committed SDL missing for ${missing.join(', ')} in ${schemaDir} — refusing to compose a partial graph`);
  process.exit(2);
}

const lines = [
  '# GENERATED by ops/compose-offline.mjs — composed from committed SDL, no running subgraphs required.',
  'federation_version: =2.9.0',
  'subgraphs:',
];
SUBGRAPHS.forEach((name, i) => {
  lines.push(`  ${name}:`);
  lines.push(`    routing_url: http://127.0.0.1:${basePort + i}/`);
  lines.push('    schema:');
  lines.push(`      file: ${join(schemaDir, `${name}.graphql`)}`);
});

const dir = mkdtempSync(join(tmpdir(), 'fg-compose-'));
const configPath = join(dir, 'supergraph.offline.yaml');
writeFileSync(configPath, `${lines.join('\n')}\n`);

// --print-config prints the generated rover config and stops: the mapping is testable without rover.
if (args.includes('--print-config')) {
  process.stdout.write(`${lines.join('\n')}\n`);
  process.exit(0);
}

if (!existsSync(roverBin)) {
  console.error(`BLOCKED: rover not found at ${roverBin} (pass --rover)`);
  process.exit(2);
}

let sdl;
try {
  sdl = execFileSync(roverBin, ['supergraph', 'compose', '--config', configPath, '--elv2-license', 'accept'], {
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
} catch (e) {
  console.error(`BLOCKED: composition failed — ${String(e.stderr ?? e.message ?? e).slice(0, 600)}`);
  process.exit(2);
}

const absent = expect.filter((f) => !sdl.includes(f));
if (absent.length) {
  console.error(`REFUSED: composed artifact is missing expected field(s): ${absent.join(', ')}`);
  process.exit(2);
}

// Routing URLs must be the ones this caller asked for, not whatever a neighbouring stack happens to serve.
const wrongRoute = SUBGRAPHS.find((n, i) => !sdl.includes(`http://127.0.0.1:${basePort + i}/`));
if (wrongRoute) {
  console.error(`REFUSED: composed artifact does not route ${wrongRoute} to port ${basePort + SUBGRAPHS.indexOf(wrongRoute)}`);
  process.exit(2);
}

mkdirSync(dirname(resolve(out)), { recursive: true });
writeFileSync(resolve(out), sdl);
console.log(`composed ${SUBGRAPHS.length} subgraphs from committed SDL -> ${out}`);
console.log(`  routing base  : http://127.0.0.1:${basePort}-${basePort + SUBGRAPHS.length - 1}/`);
console.log(`  fields checked: ${expect.join(', ')}`);
console.log(`  bytes         : ${readFileSync(resolve(out), 'utf8').length}`);
