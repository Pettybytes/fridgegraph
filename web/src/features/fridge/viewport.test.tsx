it('keeps the clicked image point fixed, clamps bounds, and preserves the normalized point through resize',()=>{
 const p={x:.35,y:.3},next=zoomAt(overview,p,2.5)
 expect(next.scale).toBe(2.5)
 expect((p.x-next.x)/next.scale).toBeCloseTo(p.x)
 expect((p.y-next.y)/next.scale).toBeCloseTo(p.y)
 for(const width of [390,1440])expect((p.x*width-next.x*width)/next.scale/width).toBeCloseTo(p.x)
 expect(clampView({scale:99,x:100,y:-100})).toEqual({scale:4,x:0,y:-3})
})
